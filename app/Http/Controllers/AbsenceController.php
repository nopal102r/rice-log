                    $dayRecords = $allMonthAbsences->get($dayStr);

                    if ($dayRecords) {
                        $in = $dayRecords->where('type', 'masuk')->first();
                        $out = $dayRecords->where('type', 'keluar')->first();
                        
                        $statusDisplay = $in ? $in->status : '-';
                        if ($in && $in->is_manual_req) {
