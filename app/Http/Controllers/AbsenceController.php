                        $rowDate = \Carbon\Carbon::createFromDate($year, $month, $day);

                        $rows[] = [
                            $rowDate->format('d M Y'),
                            $in ? $in->created_at->format('H:i') : '-',
                            $out ? $out->created_at->format('H:i') : '-',
                            $statusDisplay,
                            $in ? $in->distance_from_office : '-',
